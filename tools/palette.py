# Рампы материалов: от самого тёмного тона к самому светлому. Каждый цвет
# палитры входит ровно в одну рампу. Освещение (тени, AO, блики) сдвигает
# тон пикселя вдоль его рампы, поэтому цвет никогда не «уезжает» в чужой материал.
RAMPS = [
    ["o", "d", "m", "="],                       # тёмный
    ["1", "K", "k", "C", "c", "W"],             # крем
    ["2", "P", "p", "F", "f", "q", "Q"],        # светлое дерево
    ["3", "J", "j", "4"],                       # столешница
    ["5", "u", "v", "w", "A"],                  # тёмное дерево
    ["6", "H", "h", "G", "g", "D"],             # шалфей
    ["7", "Z", "z", "L", "l", "I"],             # сине-серый
    ["8", "x", "S", "s", "M"],                  # металл
    ["9", "T", "t", "O"],                       # мята
    ["+", "N", "n", "B", "b", "U"],             # картон
    ["0", "R", "r", "i", "V"],                  # терракота
    ["$", "Y", "y", "X"],                       # охра
    ["%", "E", "e", "a", "&"],                  # зелень
    ["(", ")", "[", "]"],                       # кожа
    ["{", "}", "<", ">"],                       # тёмно-коричневые волосы
]

RAMP_OF = {k: (ramp, i) for ramp in RAMPS for i, k in enumerate(ramp)}


def shift(key, n):
    """Тон на n ступеней светлее (n > 0) или темнее (n < 0) в той же рампе."""
    ramp, i = RAMP_OF[key]
    return ramp[max(0, min(len(ramp) - 1, i + n))]


def rgba(key):
    h = PALETTE[key].lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)


