"""Единая палитра игры. Все спрайты рисуются только этими цветами."""

PALETTE = {
    # контур и тени
    "o": "#2e2430", "d": "#4a3a48", "m": "#6b5560",
    # белый
    "W": "#fbf5e9",
    # стены (крем)
    "c": "#f1e4cc", "C": "#e2cfb0", "k": "#c9b08e",
    # дерево
    "w": "#a7744f", "v": "#8a5a3d", "u": "#6b432f",
    # шалфей (мебель)
    "g": "#8fa88f", "G": "#6f8a74", "h": "#56705d",
    # плитка (мята)
    "t": "#d7e4d6", "T": "#b5cdbb",
    # картон
    "b": "#d0a26a", "B": "#ae7f4b", "n": "#8a5f37",
    # металл
    "s": "#c4c6c8", "S": "#93969c", "x": "#666a73",
    # акценты
    "r": "#c8664f", "R": "#9a4639",
    "y": "#e6be6e",
    "l": "#7f9cb4", "L": "#5a7590",
    # зелень
    "e": "#8bab5f", "E": "#5f7f44",
}


def rgba(key):
    h = PALETTE[key].lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)


ALLOWED = {rgba(k) for k in PALETTE}
